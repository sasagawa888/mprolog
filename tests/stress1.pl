% --------------------------------
% 1. 単純な複数節
% --------------------------------

color(red).
color(green).
color(blue).

% ?- color(X).
% X = red ;
% X = green ;
% X = blue.


% --------------------------------
% 2. 本体中の単純な呼び出し
% --------------------------------

warm(red).
warm(orange).

is_warm(X) :-
    warm(X).

% ?- is_warm(X).
% X = red ;
% X = orange.


% --------------------------------
% 3. 2つの非決定的述語
% デカルト積になるか
% --------------------------------

letter(a).
letter(b).

digit(1).
digit(2).

pair(X,Y) :-
    letter(X),
    digit(Y).

% ?- pair(X,Y).
% X = a, Y = 1 ;
% X = a, Y = 2 ;
% X = b, Y = 1 ;
% X = b, Y = 2.


% --------------------------------
% 4. 後ろの述語が失敗して
% 前の述語へバックトラック
% --------------------------------

animal(cat).
animal(dog).
animal(bird).

likes_milk(cat).
likes_milk(dog).

milk_drinker(X) :-
    animal(X),
    likes_milk(X).

% ?- milk_drinker(X).
% X = cat ;
% X = dog.
%
% bird では likes_milk(bird) が失敗する。


% --------------------------------
% 5. 同じ述語を2回呼ぶ
% 成功継続と失敗継続の確認
% --------------------------------

bit(0).
bit(1).

two_bits(X,Y) :-
    bit(X),
    bit(Y).

% ?- two_bits(X,Y).
% X = 0, Y = 0 ;
% X = 0, Y = 1 ;
% X = 1, Y = 0 ;
% X = 1, Y = 1.


% --------------------------------
% 6. 軽い再帰
% --------------------------------

nat(0).
nat(s(X)) :-
    nat(X).

% 無限列挙なので途中で止める
% ?- nat(X).
% X = 0 ;
% X = s(0) ;
% X = s(s(0)) ;
% ...


% --------------------------------
% 7. 有限の再帰
% --------------------------------

count(0).
count(s(0)).
count(s(s(0))).

copy_count(X) :-
    count(X).

% ?- copy_count(X).
% X = 0 ;
% X = s(0) ;
% X = s(s(0)).


% --------------------------------
% 8. 再帰のあとに述語を実行
% 成功継続の復元確認
% --------------------------------

zero(0).

strip(0,0).
strip(s(X),Y) :-
    strip(X,Z),
    %zero(Z),
    Y = s(X).



% ?- strip(s(s(0)),X).
% X = s(s(0)).
